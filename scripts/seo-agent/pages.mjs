/**
 * The page triage for /admin/seo: every sitemap URL in one bucket (healthy · improve · consolidate ·
 * remove · watch), with a section and a plan.
 *
 *   node scripts/seo-agent/pages.mjs            → writes seo-agent/pages.json
 *
 * Sources: the sitemap from the latest snapshot (`health.json`) and, when present, the previous
 * 28-day window of the latest `gsc.json` as `demand`. The live numbers per page stay out of this
 * file: the page fetches them from Search Console, otherwise this file would age every day.
 *
 * The rules below are the source: a different triage is a change here and a new run, never hand
 * edits in the JSON. This site is young and has no page audit yet; every rule is structural.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { isoWeek } from './lib/dates.mjs';

const ROOT = 'seo-agent';

const weeks = readdirSync(`${ROOT}/data`).filter(d => /^\d{4}-W\d{2}$/.test(d)).sort();
if (!weeks.length) throw new Error('no snapshot yet: run node scripts/seo-agent/collect.mjs --only health first');
const latest = weeks.at(-1);
const health = JSON.parse(readFileSync(`${ROOT}/data/${latest}/health.json`, 'utf8')).sites.deutschtest;
let gsc = null;
try { gsc = JSON.parse(readFileSync(`${ROOT}/data/${latest}/gsc.json`, 'utf8')).sites.deutschtest; } catch {}
const toPath = url => decodeURI(url.replace(/^https?:\/\/[^/]+/, '')) || '/';
const demand = new Map((gsc?.previous?.page ?? []).map(r => [toPath(r.keys[0]), r.impressions]));

const SECTIONS = [
  { key: 'practice', label: 'Free tests', note: 'What we sell, in miniature. Tool intent: the queries AI Overviews can’t answer.' },
  { key: 'landing', label: 'Landing pages', note: 'A2-stuck, citizenship and pricing. Where the paid product is explained.' },
  { key: 'blog', label: 'Blog (DE)', note: 'Guides with a named author, review date and sources. One query, one owning page.' },
  { key: 'core', label: 'Core pages', note: 'Home, English home, about, contact.' },
  { key: 'translations', label: 'UK / RU mirrors', note: 'Machine translations, labelled as such. Watched, not pushed.' },
  { key: 'legal', label: 'Legal', note: 'Impressum, Datenschutz, AGB, Widerruf. Must exist, never rank.' },
];

function section(path) {
  if (/^\/(uk|ru)(\/|$)/.test(path)) return 'translations';
  if (/^\/gratis-test(\/|$)/.test(path)) return 'practice';
  if (/^\/(a2-zu-b1|b1-einbuergerung|preise)(\/|$)/.test(path)) return 'landing';
  if (/^\/blog(\/|$)/.test(path)) return 'blog';
  if (/^\/(impressum|datenschutz|agb|widerruf)(\/|$)/.test(path)) return 'legal';
  return 'core';
}

/** Extra guidance for a page that needs more than the section rule. Keys are paths. */
const NOTES = {};

const out = [];
for (const url of Object.keys(health.pages)) {
  const path = toPath(url);
  const sec = section(path);
  let verdict = 'healthy';
  let reason;
  let plan = null;
  if (sec === 'translations') {
    verdict = 'watch';
    reason = 'Machine translation, labelled on the page. Kept for the learner; never a ranking bet.';
    plan = { action: 'No work. If it draws German queries away from the German original, consider noindex.', owner: 'agent', when: 'later' };
  } else if (sec === 'legal') {
    reason = 'Required page; search demand is irrelevant.';
  } else if (sec === 'practice') {
    reason = 'A free test: what the site sells in miniature. Keep it, link to it from every guide.';
  } else if (sec === 'blog') {
    reason = 'A reviewed guide. Owns its query per seo/keyword-strategy.md.';
  } else {
    reason = sec === 'landing' ? 'A landing page for one audience.' : 'A core page of the site.';
  }
  if (NOTES[path]) plan = { action: NOTES[path], owner: 'agent', when: 'later' };
  out.push({ path, section: sec, verdict, reason, plan, demand: demand.get(path) ?? 0 });
}

const now = new Date();
const counts = Object.fromEntries(['healthy', 'improve', 'consolidate', 'remove', 'watch'].map(v => [v, out.filter(p => p.verdict === v).length]));

writeFileSync(`${ROOT}/pages.json`, JSON.stringify({
  $comment: 'Generated by scripts/seo-agent/pages.mjs from the sitemap in the latest health snapshot. Do not edit by hand: change the rules in the script and run it again. Search numbers per page come live from Search Console on /admin/seo.',
  updated: now.toISOString().slice(0, 10),
  week: isoWeek(now),
  sources: { sitemap: `${ROOT}/data/${latest}/health.json`, demand: gsc ? `${ROOT}/data/${latest}/gsc.json (previous window)` : null },
  sections: SECTIONS,
  counts,
  pages: out,
  planned: [],
}, null, 2) + '\n');

console.log(`pages.json: ${out.length} pages`, counts);
